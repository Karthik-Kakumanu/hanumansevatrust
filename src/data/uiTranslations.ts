export function translateText(text: string, language: Language): string {
  if (language === 'en') return text
  const leading = text.match(/^\s*/)?.[0] ?? ''
  const trailing = text.match(/\s*$/)?.[0] ?? ''
  const key = text.trim()
  const numberedLabel = key.match(/^(\d+\s*·\s*)(.+)$/)
  const translated = telugu[key] ?? (numberedLabel
    ? `${numberedLabel[1]}${telugu[numberedLabel[2]] ?? numberedLabel[2]}`
    : undefined)
  return translated ? `${leading}${translated}${trailing}` : text
}

export function translateAttribute(name: string, value: string, language: Language): string {
  if (language === 'en') return value
  if (name === 'aria-label' && value.startsWith('Copy ')) {
    return `${translateText('Copy', language)} ${value.slice('Copy '.length)}`
  }
  return translateText(value, language)
}
